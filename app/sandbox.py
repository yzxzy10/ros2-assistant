# -*- coding: utf-8 -*-
"""编译沙箱：把「看起来对」变成「真的能编译、真的能起来」。

现有校验链只到 AST（checker_code.py），它查得到 `rclpy.Node` 这类写法错误，
查不到 import 不存在的 msg、setup.py 入口写错、依赖没声明、节点一启动就崩。
本模块把这些补上：生成一个最小 ament_python 包 → colcon build → 起节点 6 秒
→ ros2 node list 确认它真的注册上了。

三种后端，结果里都会写明用的是哪种、哪个 ROS 发行版、哪个镜像：
- docker：容器里跑（默认首选，宿主机不需要装 ROS）
- local ：本机已装 ROS 时直接跑
- none  ：环境不支持时**明确降级**，绝不假装验证通过
- mock  ：仅供离线测试，结果里 backend=mock，界面会标注「模拟」

安全边界要写清楚：这是**编译校验沙箱**，不是安全隔离层。容器用
--network none / --cap-drop ALL / 内存与 pid 限额，用来跑「本系统自己生成的
代码」；不要拿它执行来路不明的第三方代码。
"""
import json
import os
import re
import shutil
import subprocess
import tempfile
import threading
import time

from . import versions

_ANSI = re.compile(r"\x1b\[[0-9;]*[A-Za-z]")
_PROBE = {}          # 进程内缓存：后端探测结果，避免每次请求都跑 docker info


# ---------------------------------------------------------------- 后端探测

def _docker_ok():
    if "docker" in _PROBE:
        return _PROBE["docker"]
    ok = False
    if shutil.which("docker"):
        try:
            r = subprocess.run(["docker", "info"], stdout=subprocess.DEVNULL,
                               stderr=subprocess.DEVNULL, timeout=8)
            ok = r.returncode == 0
        except Exception:            # noqa: BLE001
            ok = False
    _PROBE["docker"] = ok
    return ok


def _local_ok():
    if "local" in _PROBE:
        return _PROBE["local"]
    ok = bool(shutil.which("colcon")) and bool(shutil.which("ros2"))
    _PROBE["local"] = ok
    return ok


def resolve(cfg):
    """返回 (backend, reason)。backend ∈ docker/local/mock/none。

    环境变量 ROS2_VERIFY_BACKEND 可强制指定后端（测试/离线演示用），
    优先级高于配置，避免不同机器上测试结果不一致。
    """
    vcfg = (cfg.get("ros") or {}).get("verify") or {}
    want = str(vcfg.get("backend") or "auto").strip().lower()
    env_want = str(os.environ.get("ROS2_VERIFY_BACKEND") or "").strip().lower()
    if env_want in ("docker", "local", "mock", "none"):
        want = env_want
    if want == "none":
        return "none", str(vcfg.get("reason") or "编译验证已关闭（backend=none）")
    if not vcfg.get("enabled", True):
        return "none", "配置里关闭了编译验证（ros.verify.enabled=false）"
    if want == "mock":
        return "mock", "测试用模拟后端"
    if want == "docker":
        return ("docker", "") if _docker_ok() else ("none", "配置指定 docker，但 Docker 不可用")
    if want == "local":
        return ("local", "") if _local_ok() else ("none", "配置指定 local，但本机没有 colcon/ros2")
    if want == "auto":
        if _docker_ok():
            return "docker", ""
        if _local_ok():
            return "local", ""
        return "none", "本机既没有 Docker 也没有 colcon/ros2"
    return "none", "未知后端：%s" % want


def status(cfg):
    """给 /api/meta 与界面用的状态。"""
    backend, reason = resolve(cfg)
    return {
        "available": backend not in ("none",),
        "backend": backend,
        "reason": reason,
        "distro": versions.distro_name(cfg),
        "image": versions.image(cfg) if backend == "docker" else "",
    }


def warm():
    """服务启动时后台探一次，避免第一次健康检查被 docker info 拖慢。"""
    def _run():
        try:
            _docker_ok()
            _local_ok()
        except Exception:            # noqa: BLE001
            pass
    t = threading.Thread(target=_run, daemon=True)
    t.start()
    return t


# ---------------------------------------------------------------- 包骨架

def _pkg_name(spec):
    """节点名 → 合法 ROS 包名（小写字母数字下划线，字母开头）。"""
    raw = str((spec or {}).get("node_name") or (spec or {}).get("file_name") or "node")
    s = re.sub(r"[^a-z0-9_]+", "_", raw.lower()).strip("_")
    if not s or not s[0].isalpha():
        s = "pkg_" + (s or "node")
    return s[:40]


def _module_name(pkg):
    return re.sub(r"[^a-z0-9_]", "_", pkg)


def _entry_name(spec, pkg):
    """ros2 run 用的可执行名与入口函数名。"""
    raw = str((spec or {}).get("node_name") or pkg)
    s = re.sub(r"[^a-z0-9_]+", "_", raw.lower()).strip("_") or pkg
    return s


_SETUP_PY = """from setuptools import setup

package_name = '{pkg}'

setup(
    name=package_name,
    version='0.0.1',
    packages=[package_name],
    data_files=[
        ('share/ament_index/resource_index/packages', ['resource/' + package_name]),
        ('share/' + package_name, ['package.xml']),
    ],
    install_requires=['setuptools'],
    zip_safe=True,
    maintainer='student',
    maintainer_email='student@example.com',
    description='generated by ros2 learning assistant',
    license='Apache-2.0',
    tests_require=['pytest'],
    entry_points={{
        'console_scripts': [
            '{entry} = {pkg}.{module}:main',
        ],
    }},
)
"""

_PACKAGE_XML = """<?xml version="1.0"?>
<?xml-model href="http://download.ros.org/schema/package_format3.xsd" schematypens="http://www.w3.org/2001/XMLSchema"?>
<package format="3">
  <name>{pkg}</name>
  <version>0.0.1</version>
  <description>generated by ros2 learning assistant</description>
  <maintainer email="student@example.com">student</maintainer>
  <license>Apache-2.0</license>

  <depend>rclpy</depend>
  <depend>std_msgs</depend>
  <depend>geometry_msgs</depend>
  <depend>sensor_msgs</depend>
  <depend>nav_msgs</depend>

  <export>
    <build_type>ament_python</build_type>
  </export>
</package>
"""

_VERIFY_SH = """#!/usr/bin/env bash
# 由 ros2 教学助手自动生成：编译 + 启停校验脚本
source /opt/ros/{distro}/setup.bash || {{ echo "__ENV_FAIL__"; exit 3; }}
cd /ws || exit 3

echo "__STAGE__ build"
colcon build --symlink-install --packages-select {pkg} 2>&1 | tail -n 80
if [ "${{PIPESTATUS[0]}}" -ne 0 ]; then echo "__BUILD_FAIL__"; exit 2; fi
echo "__BUILD_OK__"

. install/setup.bash || {{ echo "__ENV_FAIL__"; exit 3; }}

echo "__STAGE__ run"
timeout -s INT {run_sec} ros2 run {pkg} {entry} > /tmp/node.log 2>&1 &
NODE_PID=$!
sleep {boot_wait}

echo "__NODES_BEGIN__"
timeout 5 ros2 node list 2>&1
echo "__NODES_END__"

wait $NODE_PID
echo "__NODE_RC__ $?"

echo "__NODE_LOG_BEGIN__"
tail -n 40 /tmp/node.log
echo "__NODE_LOG_END__"
exit 0
"""


def _write_pkg(ws, pkg, entry, code):
    """在 ws 下写出一个最小可编译的 ament_python 包。"""
    module = _module_name(pkg)
    pkgdir = os.path.join(ws, "src", pkg)
    inner = os.path.join(pkgdir, module)
    os.makedirs(os.path.join(pkgdir, "resource"), exist_ok=True)
    os.makedirs(inner, exist_ok=True)

    open(os.path.join(pkgdir, "resource", pkg), "w", encoding="utf-8").write("")
    open(os.path.join(pkgdir, "package.xml"), "w", encoding="utf-8").write(
        _PACKAGE_XML.format(pkg=pkg))
    open(os.path.join(pkgdir, "setup.py"), "w", encoding="utf-8").write(
        _SETUP_PY.format(pkg=pkg, module=module, entry=entry))
    open(os.path.join(pkgdir, "setup.cfg"), "w", encoding="utf-8").write(
        "[develop]\nscript_dir=$base/lib/%s\n[install]\ninstall_scripts=$base/lib/%s\n"
        % (pkg, pkg))
    open(os.path.join(inner, "__init__.py"), "w", encoding="utf-8").write("")
    open(os.path.join(inner, module + ".py"), "w", encoding="utf-8").write(code)


def _sh(cmd, timeout):
    try:
        r = subprocess.run(cmd, stdout=subprocess.PIPE, stderr=subprocess.STDOUT,
                           timeout=timeout)
        return r.returncode, r.stdout.decode("utf-8", "replace")
    except subprocess.TimeoutExpired as e:
        out = e.stdout.decode("utf-8", "replace") if e.stdout else ""
        return 124, out + "\n[sandbox] 超时（%ss）" % timeout
    except FileNotFoundError as e:
        return 127, "[sandbox] 命令不存在：%s" % e


def _parse(out):
    """从脚本输出里抽出结论。"""
    node_list = ""
    m = re.search(r"__NODES_BEGIN__(.*?)__NODES_END__", out, re.S)
    if m:
        node_list = m.group(1).strip()
    node_log = ""
    m2 = re.search(r"__NODE_LOG_BEGIN__(.*?)__NODE_LOG_END__", out, re.S)
    if m2:
        node_log = m2.group(1).strip()
    rc = None
    m3 = re.search(r"__NODE_RC__\s*(\d+)", out)
    if m3:
        rc = int(m3.group(1))
    return {
        "env_fail": "__ENV_FAIL__" in out,
        "build_ok": "__BUILD_OK__" in out,
        "build_fail": "__BUILD_FAIL__" in out,
        "nodes": node_list,
        "node_log": node_log,
        "node_rc": rc,
    }


def _tail(text, limit=2600):
    text = _ANSI.sub("", text or "").strip()
    return text[-limit:] if len(text) > limit else text


# ---------------------------------------------------------------- 主入口

def verify(cfg, code, spec):
    """编译 + 启停校验。

    返回字段固定，调用方可以无脑按 ok 判断：
    attempted / ok / backend / distro / image / stage / elapsed /
    runtime_ok / nodes / log / reason
    """
    vcfg = (cfg.get("ros") or {}).get("verify") or {}
    backend, reason = resolve(cfg)
    distro = versions.distro_name(cfg)
    base = {
        "attempted": False,
        "ok": False,
        "backend": backend,
        "distro": distro,
        "image": versions.image(cfg) if backend in ("docker", "mock") else "",
        "stage": "",
        "elapsed": 0.0,
        "runtime_ok": False,
        "nodes": "",
        "log": "",
        "reason": reason,
    }
    if backend == "none":
        return base
    if not (code or "").strip():
        base["reason"] = "代码为空，跳过编译验证"
        return base

    pkg = _pkg_name(spec)
    entry = _entry_name(spec, pkg)
    t_build = int(vcfg.get("timeout_build_sec") or 300)
    t_run = int(vcfg.get("timeout_run_sec") or 25)
    boot_wait = max(3, min(10, t_run // 3))

    if backend == "mock":
        return _verify_mock(base, pkg, entry, t_build + t_run)

    t0 = time.time()
    base["attempted"] = True
    ws = tempfile.mkdtemp(prefix="ros2sandbox_")
    try:
        _write_pkg(ws, pkg, entry, code)
        script = os.path.join(ws, "run_verify.sh")
        open(script, "w", encoding="utf-8", newline="\n").write(
            _VERIFY_SH.format(distro=distro, pkg=pkg, entry=entry,
                              run_sec=t_run, boot_wait=boot_wait))

        if backend == "docker":
            image = versions.image(cfg)
            cmd = ["docker", "run", "--rm",
                   "--network", "none",
                   "--cap-drop", "ALL",
                   "--security-opt", "no-new-privileges",
                   "--memory", "1g", "--cpus", "1", "--pids-limit", "256",
                   "-e", "ROS_LOCALHOST_ONLY=1",
                   "-e", "ROS_AUTOMATIC_DISCOVERY_RANGE=LOCALHOST",
                   "-v", "%s:/ws" % ws, "-w", "/ws",
                   image, "bash", "/ws/run_verify.sh"]
        else:
            cmd = ["bash", script]

        rc, out = _sh(cmd, timeout=t_build + t_run + 60)
        info = _parse(out)
        base["elapsed"] = round(time.time() - t0, 1)
        base["log"] = _tail(out)

        if info["env_fail"]:
            base["stage"] = "env"
            base["reason"] = "沙箱内 source 环境失败（镜像里没有 ROS 2 %s）" % distro
            return base
        if not info["build_ok"]:
            base["stage"] = "build"
            base["reason"] = "colcon build 失败"
            return base

        base["stage"] = "run"
        nodes = info["nodes"]
        base["nodes"] = nodes
        # 判定：节点进程没异常退出（超时被杀算正常，说明它还活着）
        rc_run = info["node_rc"]
        alive = rc_run in (0, 124, None)
        crashed = (not alive) or ("Traceback" in info["node_log"])
        base["runtime_ok"] = (not crashed)
        base["ok"] = (not crashed)
        if crashed:
            base["reason"] = "节点启动后异常退出（rc=%s）" % rc_run
            base["log"] = _tail(info["node_log"] or out)
        else:
            base["reason"] = ""
        return base
    finally:
        shutil.rmtree(ws, ignore_errors=True)


def _verify_mock(base, pkg, entry, budget):
    """离线测试用：读 ROS2_SANDBOX_MOCK 指向的 JSON 当结果。

    只允许在测试里开启；正常部署走 auto 永远不会选到它，
    且结果里 backend 恒为 mock，界面会显示「模拟」。
    """
    path = os.environ.get("ROS2_SANDBOX_MOCK", "")
    base["attempted"] = True
    base["stage"] = "build"
    base["elapsed"] = 1.0
    if not path or not os.path.isfile(path):
        base["reason"] = "mock 后端未配置 ROS2_SANDBOX_MOCK"
        return base
    try:
        fake = json.load(open(path, encoding="utf-8"))
    except Exception as e:           # noqa: BLE001
        base["reason"] = "mock 结果读取失败：%s" % e
        return base
    base["ok"] = bool(fake.get("ok"))
    base["stage"] = fake.get("stage", "run")
    base["runtime_ok"] = bool(fake.get("runtime_ok", base["ok"]))
    base["nodes"] = fake.get("nodes", "")
    base["log"] = _tail(fake.get("log", ""))
    base["reason"] = fake.get("reason", "")
    return base


def summary_line(result):
    """给界面/回复用的一行版本+校验说明。"""
    distro = result.get("distro")
    name = "ROS 2 " + (versions.DISTROS.get(distro, {}).get("display") or distro)
    backend = result.get("backend")
    if not result.get("attempted"):
        return "%s · 编译验证：未执行（%s）" % (name, result.get("reason") or "未启用")
    tag = "通过" if result.get("ok") else "未通过"
    stage_cn = {"build": "编译", "run": "启动", "env": "环境"}.get(result.get("stage"), "")
    extra = ""
    if backend == "mock":
        extra = "（模拟后端，仅测试）"
    elif backend == "docker" and result.get("image"):
        extra = "（%s 镜像）" % result["image"]
    return "%s · 编译验证：%s%s%s · %.1fs" % (
        name, tag, ("·" + stage_cn) if stage_cn else "", extra, result.get("elapsed") or 0)
